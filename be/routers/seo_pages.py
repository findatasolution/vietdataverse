"""Indexable, server-rendered landing pages — one per dataset.

Why this exists (2026-10-05): every chart lives behind one URL, `/fe/`, with
hash routes (`#data/portal/chart/gold`). Google does not index hash fragments,
so the site had exactly one data URL to rank with, and could not appear for
"giá vàng SJC hôm nay", "lãi suất tiết kiệm", "tỷ giá USD"... GA4 showed the
few organic visitors who did arrive were the most engaged on the site (87%
engagement, 5+ min) — the problem was volume, not fit.

Each page renders the latest figures, a sparkline (inline SVG — no JS, so
crawlers and AI assistants read it) and the recent history table straight
from `fe/data/*.json` at request time. Those files are regenerated by the
box after every crawl, so the pages are as fresh as the charts without any
build step. Nothing here touches the DB.

Rules: state the source and the date of the data on every page; never
describe a number as fresher than its own date; no forecast or advice.
"""

