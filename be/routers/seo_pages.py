# ── formatting ────────────────────────────────────────────────────────────────
def _load(name: str):
    with open(os.path.join(_DATA, name), encoding="utf-8") as f:
        return json.load(f)


def _num(x, dec: int = 0) -> str:
    """Vietnamese number format: 1.234.567,89"""
    if x is None:
        return "—"
    s = f"{x:,.{dec}f}"
    return s.replace(",", "X").replace(".", ",").replace("X", ".")


def _pct(x, dec: int = 2) -> str:
    return "—" if x is None else f"{_num(x, dec)}%"


def _vn_date(d: str) -> str:
    """'2026-10-04' → '04/10/2026'; '2026-08' → '08/2026'."""
    parts = d.split("-")
    return "/".join(reversed(parts))


def _fresh(d: str) -> str:
    """'hôm nay' only when the data really is from the last 2 days — a title
    saying 'hôm nay 24/09' on 04/10 is exactly the overclaim the rules forbid."""
    age = date.today().toordinal() - date.fromisoformat(d).toordinal()
    return "hôm nay" if age <= 2 else "mới nhất"


def _signed(x, fmt) -> str:
    if x is None:
        return "—"
    return ("+" if x > 0 else "") + fmt(x)


def _series(dates, values):
    return [(d, v) for d, v in zip(dates, values) if v is not None]


def _value_on_or_before(points, target: str):
    """Latest value dated <= target, for '1 tháng trước' style comparisons."""
    best = None
    for d, v in points:
        if d <= target:
            best = v
        else:
            break
    return best


def _shift(d: str, days: int) -> str:
    return date.fromordinal(date.fromisoformat(d).toordinal() - days).isoformat()


def _sparkline(points, w: int = 640, h: int = 140) -> str:
    vals = [v for _, v in points]
    if len(vals) < 2:
        return ""
    lo, hi = min(vals), max(vals)
    span = (hi - lo) or 1
    n = len(vals) - 1
    pts = " ".join(f"{i * w / n:.1f},{h - 8 - (v - lo) / span * (h - 16):.1f}"
                   for i, v in enumerate(vals))
    first, last = points[0][0], points[-1][0]
    return (f'<figure class="spark"><svg viewBox="0 0 {w} {h}" preserveAspectRatio="none" '
            f'role="img" aria-label="Diễn biến từ {_vn_date(first)} đến {_vn_date(last)}">'
            f'<polyline fill="none" stroke="#2f5fde" stroke-width="2" points="{pts}"/></svg>'
            f'<figcaption>{_vn_date(first)} → {_vn_date(last)} · thấp nhất {{lo}} · cao nhất {{hi}}'
            f'</figcaption></figure>')


