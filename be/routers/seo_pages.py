def _make(slug: str, builder):
    async def _endpoint():
        try:
            page = builder()
        except (OSError, KeyError, IndexError, ValueError, TypeError):
            # A missing/malformed data file must not 500 a page Google is
            # crawling; 503 tells it to come back rather than drop the URL.
            return Response(status_code=503, headers={"Retry-After": "3600"})
        return HTMLResponse(_render(page), headers={"Cache-Control": "public, max-age=900"})
    return _endpoint


